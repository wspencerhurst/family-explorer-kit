"""Aggregate research outputs into data/summary.json (for the site) and research/summary-tables.md (for reading).

Collects: notable ancestors (person 'notable' fields), notable kin and legends (line files' notableKin/legends arrays),
immigrant ancestors (person 'immigrant' fields), brick walls (well-attested ancestors with no known parent),
and statistics (tiers, generations, confidence).
"""
import json, glob, pathlib, collections, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
P = json.loads((ROOT / "data/people.json").read_text(encoding="utf-8"))
ped = {k: p for k, p in P.items() if p.get("ahnentafel")}
def ahn(p): return int(p["ahnentafel"][0])
def rel(n):
    g = n.bit_length()
    if g == 1: return "self"
    if g == 2: return "parent"
    if g == 3: return "grandparent"
    k = g - 3
    return ("great-" if k == 1 else f"{k}x-great-") + "grandparent"
def side(n):
    if n < 2: return ""
    return "paternal" if (n >> (n.bit_length() - 2)) == 2 else "maternal"

notable = sorted(({"ahnentafel": ahn(p), "name": p.get("name"), "lifespan": p.get("lifespan"), "relation": rel(ahn(p)),
                   "side": side(ahn(p)), "notable": p["notable"], "confidence": p.get("confidence"), "id": k}
                  for k, p in ped.items() if p.get("notable") and not p.get("lineFlag")), key=lambda x: x["ahnentafel"])
immigrants = sorted(({"ahnentafel": ahn(p), "name": p.get("name"), "lifespan": p.get("lifespan"), "side": side(ahn(p)),
                      "immigrant": p["immigrant"], "confidence": p.get("confidence"), "id": k}
                     for k, p in ped.items() if p.get("immigrant") and not p.get("lineFlag")),
                    key=lambda x: str((x["immigrant"] or {}).get("year") if isinstance(x["immigrant"], dict) else x["immigrant"]))
kin, legends, enslaved, enslaved_counts = {}, [], [], []
_km = ROOT / "data/keymap.json"
KEYMAP = json.loads(_km.read_text(encoding="utf-8")) if _km.exists() else {}
for f in sorted(glob.glob(str(ROOT / "research/lines/*.json"))):
    try: d = json.loads(pathlib.Path(f).read_text(encoding="utf-8"))
    except Exception: continue
    task = d.get("task") or pathlib.Path(f).stem
    for k in d.get("notableKin") or []:
        nm = (k.get("name") or "").strip()
        if nm: kin.setdefault(nm.lower(), {**k, "task": task})
    for l in d.get("legends") or []:
        legends.append({**l, "task": task})
    for e in d.get("enslavedPeople") or []:
        enslaved.append({**e, "enslaverId": KEYMAP.get(e.get("enslaver"), e.get("enslaver")), "task": task})
    for e in d.get("enslavedCounts") or []:
        enslaved_counts.append({**e, "enslaverId": KEYMAP.get(e.get("enslaver"), e.get("enslaver")), "task": task})
walls = sorted(({"ahnentafel": ahn(p), "name": p.get("name"), "lifespan": p.get("lifespan"), "relation": rel(ahn(p)),
                 "missing": [r for r in ("father", "mother") if not p.get(r) or p[r] not in P], "confidence": p.get("confidence"), "id": k}
                for k, p in ped.items()
                if ahn(p).bit_length() <= 10 and p.get("tier") in ("verified", "tree") and not p.get("lineFlag")
                and (not p.get("father") or not p.get("mother"))), key=lambda x: x["ahnentafel"])
stats = {
    "inPedigree": len(ped),
    "tiers": collections.Counter(p.get("tier") for p in ped.values()),
    "confidence": collections.Counter(p.get("confidence") for p in ped.values()),
    "maxGeneration": max(ahn(p).bit_length() for p in ped.values()),
    "pedigreeCollapse": sum(1 for p in ped.values() if p.get("routes", 1) > 1),
    "knownByGeneration": {g: c for g, c in sorted(collections.Counter(ahn(p).bit_length() for p in ped.values()).items()) if g <= 20},
}
nk_f = ROOT / "data/notable-kin.json"
cousins = json.loads(nk_f.read_text(encoding="utf-8")) if nk_f.exists() else []
out = {"notableCousins": cousins, "stats": stats, "notableAncestors": notable, "notableKin": list(kin.values()), "legends": legends,
       "immigrants": immigrants, "brickWalls": walls}
(ROOT / "data/enslaved.json").write_text(json.dumps({"people": enslaved, "counts": enslaved_counts}, ensure_ascii=False, indent=1), encoding="utf-8")
print(f"enslaved people {len(enslaved)} (enslaver resolved {sum(1 for e in enslaved if e['enslaverId'] in P)}), counts {len(enslaved_counts)}")
(ROOT / "data/summary.json").write_text(json.dumps(out, ensure_ascii=False, indent=1, default=str), encoding="utf-8")

md = ["# Summary tables (generated by scripts/build_summaries.py)", "",
      f"Ancestors in pedigree: {stats['inPedigree']:,}; deepest generation {stats['maxGeneration']}; "
      f"reached by more than one route: {stats['pedigreeCollapse']:,}",
      "Tiers: " + ", ".join(f"{k} {v:,}" for k, v in stats["tiers"].most_common()), "",
      "## Notable ancestors", "| # | Name | Lifespan | Relation | Side | Why | Conf. |", "|---|---|---|---|---|---|---|"]
md += [f"| {x['ahnentafel']} | {x['name']} | {x['lifespan'] or ''} | {x['relation']} | {x['side']} | {x['notable']} | {x['confidence']} |" for x in notable]
md += ["", "## Notable kin (not direct ancestors)", "| Name | Relationship | Via | Conf. |", "|---|---|---|---|"]
md += [f"| {k.get('name')} | {k.get('relation','')} | {k.get('via','')} | {k.get('confidence','')} |" for k in kin.values()]
md += ["", "## Notable cousins (closest 60; full list in research/notable-kin.md)", "| Notable | Born | Relationship | Common ancestor | Our-side confidence |", "|---|---|---|---|---|"]
md += [f"| {c['name']} | {c['born']} | {c['relationship']} | {c['commonAncestor']['name']} (#{c['commonAncestor']['ahnentafel']}) | {c['commonAncestor']['confidence']} |"
       for c in sorted(cousins, key=lambda c: (c['stepsSubject'] + c['stepsNotable'], -(c['fame'] or 0)))[:60]]
md += ["", "## Immigrant ancestors", "| # | Name | Lifespan | Side | Arrival | Conf. |", "|---|---|---|---|---|---|"]
for x in immigrants:
    im = x["immigrant"]; s = "; ".join(f"{k}: {v}" for k, v in im.items()) if isinstance(im, dict) else str(im)
    md.append(f"| {x['ahnentafel']} | {x['name']} | {x['lifespan'] or ''} | {x['side']} | {s} | {x['confidence']} |")
md += ["", "## Legends and verdicts", "| Legend | Verdict | Basis | Source task |", "|---|---|---|---|"]
md += [f"| {l.get('legend','')} | {l.get('verdict','')} | {str(l.get('basis',''))[:200]} | {l['task']} |" for l in legends]
md += ["", "## Brick walls (generations 2–10)", "| # | Name | Lifespan | Relation | Missing |", "|---|---|---|---|---|"]
md += [f"| {x['ahnentafel']} | {x['name']} | {x['lifespan'] or ''} | {x['relation']} | {', '.join(x['missing'])} |" for x in walls]
(ROOT / "research/summary-tables.md").write_text("\n".join(md), encoding="utf-8")
print(f"notable {len(notable)}, kin {len(kin)}, legends {len(legends)}, immigrants {len(immigrants)}, brick walls {len(walls)}")
